import type { Category } from './categories.ts';

// All UI strings, in one place: translations.ko / translations.en, grouped by screen.
// Components read them through `useLanguage().t` (lib/language.tsx), never hardcode them.
// Notice CONTENT is not translated here: it comes from the backend (`analysis.en`, generated in
// the same Gemini call as the Korean analysis). The frontend never translates or calls the AI.

export type Lang = 'ko' | 'en';
export const LANGS: { value: Lang; label: string }[] = [
  { value: 'ko', label: '한국어' },
  { value: 'en', label: 'English' },
];

/** Categories are a fixed enum, so their English names are static, not AI output. */
export const CATEGORY_EN: Record<Category, string> = {
  장학금: 'Scholarship',
  학사: 'Academic affairs',
  '모집/선발': 'Recruitment',
  '행사/특강': 'Events & talks',
  '취업/진로': 'Careers',
  국제교류: 'International',
  '시설/생활': 'Campus life',
  기타: 'Other',
};

export const categoryName = (c: Category, lang: Lang) => (lang === 'en' ? CATEGORY_EN[c] : c);

// ---------- notice content per language (from stored analysis fields only) ----------

/** English title from the analysis when there is one; the Korean original otherwise. */
export const noticeTitle = (n: NoticeListItem, lang: Lang) => (lang === 'en' ? (n.analysis?.en?.title ?? n.title) : n.title);

/** First summary line for cards. */
export function noticeSummaryLine(n: NoticeListItem, lang: Lang): string {
  const a = n.analysis;
  if (!a) return '';
  const en = lang === 'en' ? a.en : null;
  return (en ? (en.summary[0] ?? en.easyExplanation) : (a.summary[0] ?? a.easyExplanation)) ?? '';
}

/** True when English was asked for but this notice's analysis has no English version yet. */
export const englishMissing = (n: NoticeListItem, lang: Lang) => lang === 'en' && !!n.analysis && !n.analysis.en;

/** Match reasons (deterministic, computed in both languages by src/match.ts). */
export const matchReasons = (m: MatchResult, lang: Lang) => (lang === 'en' ? m.matchReasonsEn : m.matchReasons);

